import React, { useState, useEffect, useRef } from "react";
import {
  X,
  Bold,
  Italic,
  Underline,
  List,
  ListOrdered,
  Heading3,
  RotateCcw,
  Check,
  BookOpen,
  Sparkles,
  Maximize2,
  Minimize2,
  RemoveFormatting,
} from "lucide-react";

interface WeeklySummaryRichModalProps {
  isOpen: boolean;
  onClose: () => void;
  value: string;
  autoGeneratedValue: string;
  topicTitle: string;
  matchedOutcomeText?: string;
  onSave: (newValue: string) => void;
}

/**
 * Converts plain/markdown-like text or sanitized HTML into clean, safe HTML for the rich editor and exports.
 */
export function convertSummaryToRichHtml(raw: string): string {
  const text = (raw || "").trim();
  if (!text) return "";

  // If it already contains rich HTML tags from the editor, sanitize and normalize it
  if (/<(?:strong|b|em|i|u|ul|ol|li|p|h[1-6]|div|br)\b/i.test(text)) {
    return sanitizeRichSummaryHtml(text);
  }

  // Convert plain text / markdown-style bullets & bold to HTML
  const lines = text.split(/\r?\n/);
  const htmlParts: string[] = [];
  let inUl = false;
  let inOl = false;

  const closeLists = () => {
    if (inUl) {
      htmlParts.push("</ul>");
      inUl = false;
    }
    if (inOl) {
      htmlParts.push("</ol>");
      inOl = false;
    }
  };

  const formatInline = (str: string): string => {
    const escaped = str
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
    return escaped
      .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
      .replace(/__([^_]+)__/g, "<u>$1</u>")
      .replace(/(?<!\*)\*([^*\n]+)\*(?!\*)/g, "<em>$1</em>")
      .replace(
        /\b([A-ZÇĞİÖŞÜ]{1,5}\d+(?:\.\d+)*\.)(?=\s|$)/g,
        "<strong>$1</strong>"
      );
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      closeLists();
      continue;
    }

    const headingMatch = line.match(/^#{1,3}\s+(.*)$/);
    if (headingMatch) {
      closeLists();
      htmlParts.push(
        `<p><strong>${formatInline(headingMatch[1].trim())}</strong></p>`
      );
      continue;
    }

    const bulletMatch = line.match(/^[•*-]\s+(.*)$/);
    if (bulletMatch) {
      if (inOl) {
        htmlParts.push("</ol>");
        inOl = false;
      }
      if (!inUl) {
        htmlParts.push("<ul>");
        inUl = true;
      }
      htmlParts.push(`<li>${formatInline(bulletMatch[1].trim())}</li>`);
      continue;
    }

    const numMatch = line.match(/^\d+[.)]\s+(.*)$/);
    if (numMatch) {
      if (inUl) {
        htmlParts.push("</ul>");
        inUl = false;
      }
      if (!inOl) {
        htmlParts.push("<ol>");
        inOl = true;
      }
      htmlParts.push(`<li>${formatInline(numMatch[1].trim())}</li>`);
      continue;
    }

    closeLists();
    htmlParts.push(`<p>${formatInline(line)}</p>`);
  }

  closeLists();
  return htmlParts.join("");
}

/**
 * Sanitizes HTML from contentEditable, keeping only safe typographic and list tags:
 * <strong>, <b>, <em>, <i>, <u>, <ul>, <ol>, <li>, <p>, <br>
 */
export function sanitizeRichSummaryHtml(dirtyHtml: string): string {
  if (!dirtyHtml) return "";
  return dirtyHtml
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<style[\s\S]*?<\/style>/gi, "")
    .replace(/<div\b[^>]*>/gi, "<p>")
    .replace(/<\/div>/gi, "</p>")
    .replace(/<h[1-6]\b[^>]*>/gi, "<p><strong>")
    .replace(/<\/h[1-6]>/gi, "</strong></p>")
    .replace(
      /<(?!\/?(?:strong|b|em|i|u|ul|ol|li|p|br)\b)[^>]+>/gi,
      ""
    )
    .replace(/<(strong|b|em|i|u|ul|ol|li|p)\s+[^>]*>/gi, "<$1>")
    .replace(/<p>\s*<\/p>/gi, "")
    .trim();
}

/**
 * Renders the rich summary safely as React elements for OfficialPlanTable.tsx
 */
export function renderRichWeeklySummary(raw: string): React.ReactNode {
  const cleanHtml = convertSummaryToRichHtml(raw);
  if (!cleanHtml) return null;

  return (
    <div
      className="rich-weekly-summary space-y-1 text-slate-900 leading-relaxed [&_ul]:list-disc [&_ul]:pl-5 [&_ul]:my-1 [&_ol]:list-decimal [&_ol]:pl-5 [&_ol]:my-1 [&_li]:my-0.5 [&_p]:my-1 [&_strong]:font-bold [&_strong]:text-black [&_b]:font-bold [&_b]:text-black [&_em]:italic [&_i]:italic [&_u]:underline"
      dangerouslySetInnerHTML={{ __html: cleanHtml }}
    />
  );
}

export const WeeklySummaryRichModal: React.FC<WeeklySummaryRichModalProps> = ({
  isOpen,
  onClose,
  value,
  autoGeneratedValue,
  topicTitle,
  matchedOutcomeText,
  onSave,
}) => {
  const editorRef = useRef<HTMLDivElement | null>(null);
  const [isFullscreen, setIsFullscreen] = useState(false);
  const [charCount, setCharCount] = useState(0);

  useEffect(() => {
    if (isOpen && editorRef.current) {
      const initialHtml = convertSummaryToRichHtml(value || autoGeneratedValue);
      editorRef.current.innerHTML = initialHtml;
      setCharCount((editorRef.current.innerText || "").trim().length);
    }
  }, [isOpen, value, autoGeneratedValue]);

  if (!isOpen) return null;

  const syncCharCount = () => {
    if (editorRef.current) {
      setCharCount((editorRef.current.innerText || "").trim().length);
    }
  };

  const execFormatCommand = (command: string, commandValue?: string) => {
    if (!editorRef.current) return;
    editorRef.current.focus();
    document.execCommand(command, false, commandValue);
    syncCharCount();
  };

  const handleResetToAuto = () => {
    if (!editorRef.current) return;
    const resetHtml = convertSummaryToRichHtml(autoGeneratedValue);
    editorRef.current.innerHTML = resetHtml;
    syncCharCount();
  };

  const handleSave = () => {
    if (!editorRef.current) {
      onClose();
      return;
    }
    const sanitized = sanitizeRichSummaryHtml(editorRef.current.innerHTML);
    onSave(sanitized);
    onClose();
  };

  return (
    <div
      className="no-print fixed inset-0 z-50 flex items-center justify-center bg-slate-950/65 backdrop-blur-xs p-3 sm:p-6"
      role="dialog"
      aria-modal="true"
      aria-labelledby="weekly-summary-modal-title"
    >
      <div
        className={`bg-white border border-slate-200 rounded-2xl shadow-2xl flex flex-col overflow-hidden transition-all ${
          isFullscreen
            ? "w-full h-full max-w-none max-h-none rounded-none"
            : "w-full max-w-3xl max-h-[90vh]"
        }`}
      >
        {/* Modal Header */}
        <div className="flex items-center justify-between gap-4 px-5 py-4 bg-gradient-to-r from-slate-900 via-indigo-950 to-sky-950 text-white border-b border-slate-800">
          <div className="flex items-center gap-3 min-w-0">
            <div className="w-9 h-9 rounded-xl bg-sky-500/20 border border-sky-400/30 flex items-center justify-center shrink-0">
              <BookOpen className="w-4 h-4 text-sky-300" />
            </div>
            <div className="min-w-0">
              <h3
                id="weekly-summary-modal-title"
                className="text-sm sm:text-base font-bold text-white truncate"
              >
                Haftalık Özet Düzenleyici — {topicTitle || "Haftalık Konu"}
              </h3>
              <p className="text-[11px] text-sky-200/90 truncate">
                Öğrenme-Öğretme Yaşantıları · Ders Materyali &amp; Konu/Çıktı Özeti Eşleşmesi
              </p>
            </div>
          </div>

          <div className="flex items-center gap-1.5 shrink-0">
            <button
              type="button"
              onClick={() => setIsFullscreen((prev) => !prev)}
              className="p-2 rounded-lg text-slate-300 hover:text-white hover:bg-white/10 transition-colors cursor-pointer"
              title={isFullscreen ? "Normal boyuta dön" : "Tam ekran genişlet"}
            >
              {isFullscreen ? (
                <Minimize2 className="w-4 h-4" />
              ) : (
                <Maximize2 className="w-4 h-4" />
              )}
            </button>
            <button
              type="button"
              onClick={onClose}
              className="p-2 rounded-lg text-slate-300 hover:text-white hover:bg-white/10 transition-colors cursor-pointer"
              title="Kapat"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Matched Outcome Context Banner */}
        {matchedOutcomeText && (
          <div className="px-5 py-2.5 bg-sky-50/90 border-b border-sky-200/80 text-xs text-sky-950 flex items-start gap-2">
            <Sparkles className="w-3.5 h-3.5 text-sky-700 shrink-0 mt-0.5" />
            <div className="min-w-0">
              <span className="font-semibold">Eşleşen Konu ve Çıktı Özeti: </span>
              <span className="text-slate-700">{matchedOutcomeText}</span>
            </div>
          </div>
        )}

        {/* Rich Text Formatting Toolbar */}
        <div className="px-5 py-2.5 bg-slate-100 border-b border-slate-200 flex flex-wrap items-center justify-between gap-2">
          <div className="flex flex-wrap items-center gap-1">
            <button
              type="button"
              onClick={() => execFormatCommand("bold")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-semibold bg-white border border-slate-300 text-slate-800 hover:bg-slate-50 hover:border-indigo-400 transition-colors cursor-pointer shadow-2xs"
              title="Kalın (Ctrl+B)"
            >
              <Bold className="w-3.5 h-3.5" />
              <span>Kalın</span>
            </button>

            <button
              type="button"
              onClick={() => execFormatCommand("italic")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-medium bg-white border border-slate-300 text-slate-800 hover:bg-slate-50 hover:border-indigo-400 transition-colors cursor-pointer shadow-2xs"
              title="İtalik (Ctrl+I)"
            >
              <Italic className="w-3.5 h-3.5" />
              <span>İtalik</span>
            </button>

            <button
              type="button"
              onClick={() => execFormatCommand("underline")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-medium bg-white border border-slate-300 text-slate-800 hover:bg-slate-50 hover:border-indigo-400 transition-colors cursor-pointer shadow-2xs"
              title="Altı Çizili (Ctrl+U)"
            >
              <Underline className="w-3.5 h-3.5" />
              <span>Altı Çizili</span>
            </button>

            <span className="h-5 w-px bg-slate-300 mx-1" aria-hidden="true" />

            <button
              type="button"
              onClick={() => execFormatCommand("insertUnorderedList")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-medium bg-white border border-slate-300 text-slate-800 hover:bg-slate-50 hover:border-indigo-400 transition-colors cursor-pointer shadow-2xs"
              title="Madde İşaretli Liste"
            >
              <List className="w-3.5 h-3.5" />
              <span>Madde Listesi</span>
            </button>

            <button
              type="button"
              onClick={() => execFormatCommand("insertOrderedList")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-medium bg-white border border-slate-300 text-slate-800 hover:bg-slate-50 hover:border-indigo-400 transition-colors cursor-pointer shadow-2xs"
              title="Numaralı Liste"
            >
              <ListOrdered className="w-3.5 h-3.5" />
              <span>Numaralı Liste</span>
            </button>

            <button
              type="button"
              onClick={() => execFormatCommand("formatBlock", "H3")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-medium bg-white border border-slate-300 text-slate-800 hover:bg-slate-50 hover:border-indigo-400 transition-colors cursor-pointer shadow-2xs"
              title="Alt Başlık"
            >
              <Heading3 className="w-3.5 h-3.5" />
              <span>Başlık</span>
            </button>

            <button
              type="button"
              onClick={() => execFormatCommand("removeFormat")}
              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-medium bg-white border border-slate-300 text-slate-700 hover:bg-slate-50 transition-colors cursor-pointer shadow-2xs"
              title="Biçimlendirmeyi Temizle"
            >
              <RemoveFormatting className="w-3.5 h-3.5" />
              <span className="hidden sm:inline">Biçimi Temizle</span>
            </button>
          </div>

          <button
            type="button"
            onClick={handleResetToAuto}
            className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-semibold bg-amber-50 border border-amber-300 text-amber-900 hover:bg-amber-100 transition-colors cursor-pointer"
            title="Ders materyalinden otomatik çekilen özete geri dön"
          >
            <RotateCcw className="w-3.5 h-3.5 text-amber-700" />
            <span>Materyalden Yeniden Çek</span>
          </button>
        </div>

        {/* Rich ContentEditable Area */}
        <div className="flex-1 overflow-y-auto p-5 bg-slate-50/60">
          <div
            ref={editorRef}
            contentEditable
            suppressContentEditableWarning
            onInput={syncCharCount}
            className="min-h-[260px] w-full rounded-xl border border-slate-300 bg-white p-4 text-sm text-slate-900 leading-relaxed focus:border-indigo-600 focus:ring-2 focus:ring-indigo-500/15 focus:outline-none shadow-2xs [&_ul]:list-disc [&_ul]:pl-6 [&_ul]:my-2 [&_ol]:list-decimal [&_ol]:pl-6 [&_ol]:my-2 [&_li]:my-1 [&_p]:my-1.5 [&_h3]:font-bold [&_h3]:text-base [&_h3]:mt-2 [&_h3]:mb-1 [&_strong]:font-bold [&_b]:font-bold [&_em]:italic [&_i]:italic [&_u]:underline"
          />
          <div className="mt-2 flex items-center justify-between text-[11px] text-slate-500">
            <span>
              Metni seçerek üstteki araç çubuğundan kalın, italik, altı çizili veya
              madde işaretli liste uygulayabilirsiniz.
            </span>
            <span className="tabular-nums font-medium">{charCount} karakter</span>
          </div>
        </div>

        {/* Modal Footer */}
        <div className="px-5 py-3.5 bg-white border-t border-slate-200 flex items-center justify-end gap-2.5">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 rounded-lg border border-slate-300 bg-white hover:bg-slate-50 text-xs font-semibold text-slate-700 transition-colors cursor-pointer"
          >
            Vazgeç
          </button>
          <button
            type="button"
            onClick={handleSave}
            className="inline-flex items-center gap-1.5 px-4 py-2 rounded-lg bg-indigo-950 hover:bg-indigo-900 text-xs font-semibold text-white shadow-xs transition-colors cursor-pointer"
          >
            <Check className="w-3.5 h-3.5 text-amber-300" />
            <span>Özeti Plana Uygula</span>
          </button>
        </div>
      </div>
    </div>
  );
};
